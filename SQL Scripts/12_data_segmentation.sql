    Project:
    SQL Exploratory Data Analysis Project

    Purpose:
    Segment customers and products into meaningful business groups based on
    purchasing behavior, revenue contribution, and product performance.

    Customer Segmentation:
        1. Customer revenue
        2. Order frequency
        3. Customer activity
        4. High / Medium / Low value customers

    Product Segmentation:
        1. Product revenue
        2. Product price range
        3. High / Medium / Low performing products

    Business Use:
    Helps identify high-value customers, understand customer purchasing
    behavior, and classify products based on their business performance.

===============================================================================
