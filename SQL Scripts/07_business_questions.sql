-- ==========================================================
-- BUSINESS AREA 6: PRODUCT & CUSTOMER RELATIONSHIP
-- ==========================================================


-- Q23. Which product category is most popular among customers?

SELECT TOP 10
    p.category,
    COUNT(DISTINCT f.customer_key) AS unique_customers,
    SUM(f.quantity) AS total_quantity_sold,
    SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_products AS p
    ON f.product_key = p.product_key
GROUP BY p.category
ORDER BY unique_customers DESC;


------------------------------------------------------------

-- Q24. Which products are purchased by the largest number of customers?

SELECT TOP 10
    p.product_name,
    COUNT(DISTINCT f.customer_key) AS unique_customers,
    SUM(f.quantity) AS total_quantity_sold
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_products AS p
    ON f.product_key = p.product_key
GROUP BY p.product_name
ORDER BY unique_customers DESC;


-- ==========================================================
-- BUSINESS AREA 7: BUSINESS CONCENTRATION
-- ==========================================================


-- Q25. What percentage of total revenue comes from the top 10 customers?

WITH customer_revenue AS
(
    SELECT
        customer_key,
        SUM(sales_amount) AS total_revenue
    FROM gold.fact_sales
    GROUP BY customer_key
),
ranked_customers AS
(
    SELECT
        customer_key,
        total_revenue,
        ROW_NUMBER() OVER (
            ORDER BY total_revenue DESC
        ) AS customer_rank
    FROM customer_revenue
)
SELECT
    SUM(total_revenue) AS top_10_customer_revenue,
    (
        SELECT SUM(sales_amount)
        FROM gold.fact_sales
    ) AS total_business_revenue,
    SUM(total_revenue) * 100.0 /
        NULLIF(
            (
                SELECT SUM(sales_amount)
                FROM gold.fact_sales
            ), 0
        ) AS top_10_revenue_percentage
FROM ranked_customers
WHERE customer_rank <= 10;


------------------------------------------------------------

-- Q26. What percentage of total revenue comes from the top 10 products?

WITH product_revenue AS
(
    SELECT
        product_key,
        SUM(sales_amount) AS total_revenue
    FROM gold.fact_sales
    GROUP BY product_key
),
ranked_products AS
(
    SELECT
        product_key,
        total_revenue,
        ROW_NUMBER() OVER (
            ORDER BY total_revenue DESC
        ) AS product_rank
    FROM product_revenue
)
SELECT
    SUM(total_revenue) AS top_10_product_revenue,
    (
        SELECT SUM(sales_amount)
        FROM gold.fact_sales
    ) AS total_business_revenue,
    SUM(total_revenue) * 100.0 /
        NULLIF(
            (
                SELECT SUM(sales_amount)
                FROM gold.fact_sales
            ), 0
        ) AS top_10_revenue_percentage
FROM ranked_products
WHERE product_rank <= 10;


-- ==========================================================
-- BUSINESS AREA 8: ORDER VALUE ANALYSIS
-- ==========================================================


-- Q27. What is the average order value by year?

SELECT
    YEAR(order_date) AS order_year,
    SUM(sales_amount) AS total_revenue,
    COUNT(DISTINCT order_name) AS total_orders,
    SUM(sales_amount) * 1.0
        / NULLIF(COUNT(DISTINCT order_name), 0)
        AS average_order_value
FROM gold.fact_sales
GROUP BY YEAR(order_date)
ORDER BY order_year;


------------------------------------------------------------

-- Q28. Which customers have an average order value above
-- the overall average order value?

WITH customer_orders AS
(
    SELECT
        customer_key,
        COUNT(DISTINCT order_name) AS total_orders,
        SUM(sales_amount) AS total_revenue
    FROM gold.fact_sales
    GROUP BY customer_key
)
SELECT
    customer_key,
    total_orders,
    total_revenue,
    total_revenue * 1.0
        / NULLIF(total_orders, 0) AS average_order_value
FROM customer_orders
WHERE
    total_revenue * 1.0 / NULLIF(total_orders, 0)
    >
    (
        SELECT
            SUM(sales_amount) * 1.0
            / NULLIF(COUNT(DISTINCT order_name), 0)
        FROM gold.fact_sales
    )
ORDER BY average_order_value DESC;


-- ==========================================================
-- BUSINESS AREA 9: TOP PRODUCT WITHIN EACH CATEGORY
-- ==========================================================


-- Q29. What is the highest-revenue product within each category?

WITH product_revenue AS
(
    SELECT
        p.category,
        p.product_name,
        SUM(f.sales_amount) AS total_revenue
    FROM gold.fact_sales AS f
    LEFT JOIN gold.dim_products AS p
        ON f.product_key = p.product_key
    GROUP BY
        p.category,
        p.product_name
),
ranked_products AS
(
    SELECT
        category,
        product_name,
        total_revenue,
        ROW_NUMBER() OVER (
            PARTITION BY category
            ORDER BY total_revenue DESC
        ) AS product_rank
    FROM product_revenue
)
SELECT
    category,
    product_name,
    total_revenue
FROM ranked_products
WHERE product_rank = 1
ORDER BY category;


-- ==========================================================
-- BUSINESS AREA 10: FINAL EXECUTIVE SUMMARY
-- ==========================================================


-- Q30. Generate a high-level business KPI summary.

SELECT
    SUM(sales_amount) AS total_revenue,
    COUNT(DISTINCT order_name) AS total_orders,
    SUM(quantity) AS total_items_sold,
    COUNT(DISTINCT customer_key) AS active_customers,
    COUNT(DISTINCT product_key) AS products_sold,
    AVG(price) AS average_selling_price,
    SUM(sales_amount) * 1.0
        / NULLIF(COUNT(DISTINCT order_name), 0)
        AS average_order_value,
    SUM(sales_amount) * 1.0
        / NULLIF(COUNT(DISTINCT customer_key), 0)
        AS revenue_per_customer
FROM gold.fact_sales;
