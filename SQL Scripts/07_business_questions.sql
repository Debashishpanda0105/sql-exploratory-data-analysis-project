-- ==========================================================
-- BUSINESS AREA 1: SALES PERFORMANCE
-- ==========================================================


-- Q1. What is the total revenue generated by the business?

SELECT
    SUM(sales_amount) AS total_revenue
FROM gold.fact_sales;


------------------------------------------------------------

-- Q2. What is the total number of orders and items sold?

SELECT
    COUNT(DISTINCT order_name) AS total_orders,
    SUM(quantity) AS total_items_sold
FROM gold.fact_sales;


------------------------------------------------------------

-- Q3. What is the average revenue generated per order?

SELECT
    SUM(sales_amount) * 1.0
    / NULLIF(COUNT(DISTINCT order_name), 0) AS average_order_value
FROM gold.fact_sales;


------------------------------------------------------------

-- Q4. How does revenue change from year to year?

SELECT
    YEAR(order_date) AS order_year,
    SUM(sales_amount) AS total_revenue,
    COUNT(DISTINCT order_name) AS total_orders
FROM gold.fact_sales
GROUP BY YEAR(order_date)
ORDER BY order_year;


------------------------------------------------------------

-- Q5. Which year generated the highest revenue?

SELECT TOP 1
    YEAR(order_date) AS order_year,
    SUM(sales_amount) AS total_revenue
FROM gold.fact_sales
GROUP BY YEAR(order_date)
ORDER BY total_revenue DESC;


-- ==========================================================
-- BUSINESS AREA 2: CUSTOMER ANALYSIS
-- ==========================================================


-- Q6. How many customers have actually placed an order?

SELECT
    COUNT(DISTINCT customer_key) AS active_customers
FROM gold.fact_sales;


------------------------------------------------------------

-- Q7. What percentage of customers have placed at least one order?

SELECT
    COUNT(DISTINCT fs.customer_key) * 100.0
    / NULLIF(COUNT(DISTINCT dc.customer_key), 0)
        AS customer_conversion_rate
FROM gold.dim_customers AS dc
LEFT JOIN gold.fact_sales AS fs
    ON dc.customer_key = fs.customer_key;


------------------------------------------------------------

-- Q8. Who are the top 10 highest-value customers?

SELECT TOP 10
    c.customer_key,
    c.first_name,
    c.last_name,
    SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_customers AS c
    ON f.customer_key = c.customer_key
GROUP BY
    c.customer_key,
    c.first_name,
    c.last_name
ORDER BY total_revenue DESC;


------------------------------------------------------------

-- Q9. Which customers have placed the most orders?

SELECT TOP 10
    c.customer_key,
    c.first_name,
    c.last_name,
    COUNT(DISTINCT f.order_name) AS total_orders
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_customers AS c
    ON f.customer_key = c.customer_key
GROUP BY
    c.customer_key,
    c.first_name,
    c.last_name
ORDER BY total_orders DESC;


------------------------------------------------------------

-- Q10. Which customers generate high revenue but place relatively
-- few orders?

SELECT TOP 10
    c.customer_key,
    c.first_name,
    c.last_name,
    COUNT(DISTINCT f.order_name) AS total_orders,
    SUM(f.sales_amount) AS total_revenue,
    SUM(f.sales_amount) * 1.0
        / NULLIF(COUNT(DISTINCT f.order_name), 0)
        AS average_order_value
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_customers AS c
    ON f.customer_key = c.customer_key
GROUP BY
    c.customer_key,
    c.first_name,
    c.last_name
HAVING COUNT(DISTINCT f.order_name) > 0
ORDER BY average_order_value DESC;


-- ==========================================================
-- BUSINESS AREA 3: PRODUCT ANALYSIS
-- ==========================================================


-- Q11. Which products generate the highest revenue?

SELECT TOP 10
    p.product_name,
    SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_products AS p
    ON f.product_key = p.product_key
GROUP BY p.product_name
ORDER BY total_revenue DESC;


------------------------------------------------------------

-- Q12. Which products have the highest sales volume?

SELECT TOP 10
    p.product_name,
    SUM(f.quantity) AS total_quantity_sold
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_products AS p
    ON f.product_key = p.product_key
GROUP BY p.product_name
ORDER BY total_quantity_sold DESC;


------------------------------------------------------------

-- Q13. Which products generate the lowest revenue?

SELECT TOP 10
    p.product_name,
    SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_products AS p
    ON f.product_key = p.product_key
GROUP BY p.product_name
ORDER BY total_revenue ASC;


------------------------------------------------------------

-- Q14. Which categories generate the most revenue?

SELECT
    p.category,
    SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_products AS p
    ON f.product_key = p.product_key
GROUP BY p.category
ORDER BY total_revenue DESC;


------------------------------------------------------------

-- Q15. Which category sells the highest number of items?

SELECT TOP 1
    p.category,
    SUM(f.quantity) AS total_quantity_sold
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_products AS p
    ON f.product_key = p.product_key
GROUP BY p.category
ORDER BY total_quantity_sold DESC;


------------------------------------------------------------

-- Q16. Which categories have many products but relatively low revenue?

SELECT
    p.category,
    COUNT(DISTINCT p.product_key) AS total_products,
    SUM(f.sales_amount) AS total_revenue,
    SUM(f.sales_amount) * 1.0
        / NULLIF(COUNT(DISTINCT p.product_key), 0)
        AS revenue_per_product
FROM gold.dim_products AS p
LEFT JOIN gold.fact_sales AS f
    ON p.product_key = f.product_key
GROUP BY p.category
ORDER BY revenue_per_product ASC;


-- ==========================================================
-- BUSINESS AREA 4: GEOGRAPHIC ANALYSIS
-- ==========================================================


-- Q17. Which countries generate the most revenue?

SELECT
    c.country,
    SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_customers AS c
    ON f.customer_key = c.customer_key
GROUP BY c.country
ORDER BY total_revenue DESC;


------------------------------------------------------------

-- Q18. Which countries have the highest number of customers?

SELECT
    country,
    COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY country
ORDER BY total_customers DESC;


------------------------------------------------------------

-- Q19. Which countries have the highest number of orders?

SELECT
    c.country,
    COUNT(DISTINCT f.order_name) AS total_orders
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_customers AS c
    ON f.customer_key = c.customer_key
GROUP BY c.country
ORDER BY total_orders DESC;


------------------------------------------------------------

-- Q20. Which countries generate the highest revenue per customer?

SELECT
    c.country,
    COUNT(DISTINCT c.customer_key) AS total_customers,
    SUM(f.sales_amount) AS total_revenue,
    SUM(f.sales_amount) * 1.0
        / NULLIF(COUNT(DISTINCT c.customer_key), 0)
        AS revenue_per_customer
FROM gold.fact_sales AS f
LEFT JOIN gold.dim_customers AS c
    ON f.customer_key = c.customer_key
GROUP BY c.country
ORDER BY revenue_per_customer DESC;


-- ==========================================================
-- BUSINESS AREA 5: CUSTOMER DEMOGRAPHICS
