 Script Name : 07_business_questions.sql

 Description :
     Answer real-world business questions using the Gold Layer of the
     Data Warehouse.

     This script applies SQL aggregation, joins, filtering, date analysis,
     conditional logic, and window functions to translate raw business data
     into actionable insights.

     The analysis focuses on sales performance, customer behavior, product
     performance, geographic trends, and business concentration.

     This script represents the final analytical stage of the SQL
     Exploratory Data Analysis project.
